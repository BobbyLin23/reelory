export const messages: Record<Locale, Record<MessageKey, Message>> = {
  en,
  "zh-CN": zh,
};

const numberFormats: Record<Locale, Intl.NumberFormat> = {
  en: new Intl.NumberFormat("en"),
  "zh-CN": new Intl.NumberFormat("zh-CN"),
};

const pluralForm = (locale: Locale, params: MessageParams): keyof PluralMessage =>
  locale === "en" && params.count === 1 ? "one" : "other";

/** Resolves a message and fills its `{placeholders}`; numbers follow the interface locale. */
export const translate = (locale: Locale, key: MessageKey, params: MessageParams = {}): string => {
  const message = messages[locale][key];
  const template = typeof message === "string" ? message : message[pluralForm(locale, params)];

  return template.replaceAll(/\{(\w+)\}/gu, (match, name: string) => {
    const value = params[name];
    if (value === undefined) {
      // A template handed to a component, such as "{position} of {count}", keeps its placeholders.
      return match;
    }
    return typeof value === "number" ? numberFormats[locale].format(value) : value;
  });
};
